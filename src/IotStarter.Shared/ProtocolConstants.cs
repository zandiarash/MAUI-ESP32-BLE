// Shared between the nanoFramework firmware and the .NET 11 app.
// Keep to the conservative C# subset: no generics, LINQ, records, nullable annotations
// or file-scoped namespaces. See docs/protocol.md for the specification.
#nullable disable

namespace IotStarter.Shared
{
    /// <summary>
    /// Values both sides of the BLE and network protocols must agree on.
    /// </summary>
    public static class ProtocolConstants
    {
        // ---- Versions -------------------------------------------------------------------

        /// <summary>BLE provisioning protocol version (advertised and in the Info characteristic).</summary>
        public const byte ProtocolVersion = 1;

        /// <summary>HTTP API version (the "/api/v1" prefix and the "api" field).</summary>
        public const int ApiVersion = 1;

        // ---- BLE identifiers (freshly generated random 128-bit UUIDs) --------------------

        public const string ServiceUuid = "54173fa7-8b86-4bf4-acd4-a120112bf9e3";
        public const string InfoCharacteristicUuid = "cd51670e-5dc7-4022-8df5-01e6abf15b43";
        public const string StateCharacteristicUuid = "6e4e8482-ec16-42f9-bf02-0e892e1af341";
        public const string CommandCharacteristicUuid = "5f3311b1-56db-42d6-bd50-2f07bad65599";
        public const string ResultCharacteristicUuid = "b6474bd8-690e-4bf4-8fa3-2c303a31ee4e";

        // ---- Advertising ----------------------------------------------------------------

        /// <summary>Bluetooth SIG test company ID. Replace with an assigned ID before shipping.</summary>
        public const ushort ManufacturerCompanyId = 0xFFFF;

        /// <summary>Manufacturer data payload after the company ID: version(1) model(2) shortId(3).</summary>
        public const int ManufacturerPayloadLength = 6;

        /// <summary>Default BLE local-name prefix; the name is PREFIX-XXXX (last 4 hex digits of the device ID).</summary>
        public const string BleNamePrefix = "IOT";

        // ---- Framing --------------------------------------------------------------------

        /// <summary>Default ATT MTU (23) minus the 3-byte ATT header.</summary>
        public const int DefaultChunkSize = 20;

        /// <summary>Largest chunk ever sent (ATT MTU 247 minus 3).</summary>
        public const int MaxChunkSize = 244;

        /// <summary>Header bytes in every chunk: [index | END flag][message id].</summary>
        public const int ChunkHeaderSize = 2;

        /// <summary>Bit 7 of the first chunk byte marks the final chunk of a message.</summary>
        public const byte ChunkEndFlag = 0x80;

        /// <summary>Bits 0..6 of the first chunk byte hold the chunk index.</summary>
        public const byte ChunkIndexMask = 0x7F;

        /// <summary>Largest reassembled message, including type byte and CRC.</summary>
        public const int MaxMessageSize = 512;

        /// <summary>A message is discarded if the next chunk takes longer than this.</summary>
        public const int ReassemblyTimeoutMs = 3000;

        /// <summary>Message overhead: type byte + CRC-16.</summary>
        public const int MessageOverhead = 3;

        // ---- Credentials ----------------------------------------------------------------

        public const int MaxSsidBytes = 32;
        public const int MinPassphraseLength = 8;
        public const int MaxPassphraseLength = 63;

        /// <summary>Random per-device API token generated by the app.</summary>
        public const int TokenBytes = 32;

        /// <summary>Token as sent in the HTTP header: lowercase hex.</summary>
        public const int TokenHexLength = 64;

        // ---- Lengths of fixed-layout characteristics -------------------------------------

        /// <summary>Info: ver(1) model(2) deviceId(6) fw(3) caps(2).</summary>
        public const int InfoLength = 14;

        /// <summary>State: state(1) error(1) ipv4(4).</summary>
        public const int StateLength = 6;

        public const int DeviceIdBytes = 6;
        public const int ShortIdBytes = 3;

        // ---- Timing (milliseconds unless noted) -----------------------------------------

        /// <summary>Upper bound for the device's Wi-Fi join attempt during provisioning.</summary>
        public const int WifiJoinTimeoutMs = 30000;

        /// <summary>How long the device waits for a DHCP lease after association.</summary>
        public const int DhcpTimeoutMs = 15000;

        /// <summary>How long a Wi-Fi scan may take on the device.</summary>
        public const int WifiScanTimeoutMs = 10000;

        /// <summary>Delay between the final BLE notification and the reboot.</summary>
        public const int FinalStatusDelayMs = 1500;

        /// <summary>The app gives up on a provisioning attempt after this long without a final state.</summary>
        public const int AppProvisioningTimeoutMs = 60000;

        /// <summary>Normal mode: reboot into the recovery provisioning window after this long offline.</summary>
        public const int OfflineBeforeRecoveryWindowMs = 5 * 60 * 1000;

        /// <summary>Length of the token-protected recovery provisioning window.</summary>
        public const int RecoveryWindowMs = 5 * 60 * 1000;

        /// <summary>Hold time on the reset button for a factory reset.</summary>
        public const int FactoryResetHoldMs = 5000;

        // ---- Network --------------------------------------------------------------------

        public const int HttpPort = 80;

        /// <summary>UDP port for the broadcast discovery probe.</summary>
        public const int DiscoveryPort = 48731;

        /// <summary>DNS-SD service type, without the trailing ".local".</summary>
        public const string MdnsServiceType = "_iotstarter._tcp";

        /// <summary>Discovery probe: ASCII "IOTS?" followed by the protocol version.</summary>
        public const string DiscoveryProbeMagic = "IOTS?";
    }
}
